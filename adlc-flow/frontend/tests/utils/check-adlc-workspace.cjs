const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");

const root = path.resolve(__dirname, "../../../..");
const output = path.resolve(__dirname, "../../test-results/adlc-workspace");
fs.mkdirSync(output, { recursive: true });
const definitions = ["coding-agent/0.2.0", "approval/0.1.0", "skilltree-authoring-deepseek-harness/0.1.0"].map(ref => {
  const p = JSON.parse(fs.readFileSync(path.join(root, "adlc_components/packages", ref, "package.json"), "utf8"));
  return { ...p, content_digest: "browser-fixture", lifecycle_status: p.status };
});
const checks = [];
const check = (label, condition) => { assert.ok(condition, label); checks.push(label); };
(async () => {
  let browser;
  try { browser = await chromium.launch({ headless: true }); }
  catch { browser = await chromium.launch({ headless: true, executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe" }); }
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const flowId = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
  let saved, patches = 0;
  await context.route("**/api/v1/**", async route => {
    const url = new URL(route.request().url()), method = route.request().method();
    if (url.pathname.endsWith("/node-packages")) return route.fulfill({ json: definitions });
    if (url.pathname.endsWith("/local-projects")) return route.fulfill({ json: [] });
    if (method === "PATCH" && url.pathname.endsWith(`/flows/${flowId}`)) {
      saved = { ...saved, id: flowId, ...route.request().postDataJSON(), updated_at: new Date().toISOString() }; patches++;
      return route.fulfill({ json: saved });
    }
    if (url.pathname.includes("/validate")) return route.fulfill({ json: { valid: true, issues: [], warnings: [] } });
    if (url.pathname.includes("/flows")) return route.fulfill({ json: saved ?? { id: flowId, name: "Implement user management", description: "" } });
    return route.fulfill({ json: {} });
  });
  try {
    await page.goto("http://127.0.0.1:3011/tests/fixtures/adlc-workspace.html", { waitUntil: "networkidle" });
    await page.getByRole("button", { name: "Use coding starter" }).click();
    await page.waitForFunction(() => window.adlcFixture.state().nodes.length === 3);
    await page.getByLabel("Requirement", { exact: true }).fill("Implement user CRUD and pass the protected checks.");
    await page.getByRole("button", { name: /^Save stage$/i }).click();
    await page.getByRole("button", { name: "Close stage inspector" }).click();
    let state = await page.evaluate(() => window.adlcFixture.state());
    check("Starter has three independent stages and two edges", state.nodes.length === 3 && state.edges.length === 2);
    check("Requirement is saved as a literal authoring input", state.nodes[0].data.adlcDraft.requirement.includes("CRUD"));
    const canvas = page.getByTestId("adlc-workspace-canvas");
    check("Canvas occupies more than 75 percent of desktop width with inspector closed", (await canvas.boundingBox()).width / 1440 > .75);
    await page.getByRole("button", { name: "Zoom in", exact: true }).click();
    await page.waitForTimeout(220);
    let zoomed = await page.evaluate(() => window.adlcFixture.state().viewport);
    check("Zoom in increases viewport scale", zoomed.zoom > state.viewport.zoom);
    await page.getByRole("button", { name: "Zoom out", exact: true }).click();
    await page.waitForTimeout(220);
    const out = await page.evaluate(() => window.adlcFixture.state().viewport);
    check("Zoom out decreases viewport scale", out.zoom < zoomed.zoom);
    await page.getByRole("button", { name: "Reset zoom to 100 percent" }).click();
    await page.waitForTimeout(220);
    check("Zoom reset sets 100 percent", Math.abs((await page.evaluate(() => window.adlcFixture.state().viewport.zoom)) - 1) < .01);
    await page.evaluate(() => window.adlcFixture.approveLayout());
    const moveBefore = await page.evaluate(() => window.adlcFixture.state());
    const nodeHeader = page.getByTestId(`workspace-stage-${moveBefore.nodes[1].id}`).locator("header");
    const nodeRect = await nodeHeader.boundingBox();
    await page.mouse.move(nodeRect.x + 80, nodeRect.y + 20); await page.mouse.down(); await page.mouse.move(nodeRect.x + 125, nodeRect.y + 60, { steps: 12 }); await page.mouse.up();
    const moved = await page.evaluate(() => window.adlcFixture.state());
    check("Moving a stage retains dependencies", moved.edges.length === 2 && moved.nodes[1].position.x !== moveBefore.nodes[1].position.x);
    check("Moving a stage retains the accepted plan", moved.plan?.execution_plan_id === "fixture-approved");
    await page.getByRole("button", { name: "Arrange", exact: true }).click();
    check("Arrange retains the accepted plan", (await page.evaluate(() => window.adlcFixture.state().plan?.execution_plan_id)) === "fixture-approved");
    await page.getByRole("button", { name: "Edit workflow details" }).click();
    await page.getByLabel("Workflow name", { exact: true }).fill("User management workflow");
    await page.getByRole("button", { name: /^Save workflow$/i }).click();
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    state = await page.evaluate(() => window.adlcFixture.state());
    check("Renaming saves workflow details and retains the accepted plan", state.flow.name === "User management workflow" && state.plan?.execution_plan_id === "fixture-approved");
    await page.getByRole("button", { name: "Edit workflow details" }).click();
    await page.getByLabel("Outcome", { exact: true }).fill("Deliver user management with protected verification checks.");
    await page.getByRole("button", { name: /^Save workflow$/i }).click();
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    state = await page.evaluate(() => window.adlcFixture.state());
    check("Changing the outcome saves it and requires a newly reviewed plan", state.flow.description.includes("protected verification") && state.plan === null);
    await page.evaluate(() => window.adlcFixture.approveLayout());
    const rect = await canvas.boundingBox();
    const beforePan = await page.evaluate(() => window.adlcFixture.state().viewport);
    await page.mouse.move(rect.x + rect.width * .7, rect.y + rect.height * .8); await page.mouse.down(); await page.mouse.move(rect.x + rect.width * .7 - 110, rect.y + rect.height * .8 - 70, { steps: 12 }); await page.mouse.up();
    const afterPan = await page.evaluate(() => window.adlcFixture.state().viewport);
    check("Dragging empty canvas pans the viewport", afterPan.x !== beforePan.x && afterPan.y !== beforePan.y);
    const security = page.getByRole("button", { name: "Add Security Scan", exact: true });
    await security.scrollIntoViewIfNeeded(); const securityRect = await security.boundingBox();
    await page.mouse.move(securityRect.x + 70, securityRect.y + 20); await page.mouse.down(); await page.mouse.move(rect.x + rect.width * .5, rect.y + rect.height * .6, { steps: 20 }); await page.mouse.up();
    await page.waitForFunction(() => window.adlcFixture.state().nodes.length === 4);
    check("Pointer dragging a package adds it at a canvas position", (await page.evaluate(() => window.adlcFixture.state().nodes[3].data.adlcDraft.kind)) === "PLANNED_PACKAGE");
    check("Adding a stage revokes the reviewed draft plan", (await page.evaluate(() => window.adlcFixture.state().plan)) === null);
    check("WIP draft disables plan review", await page.getByTestId("preview-adlc-plan-button").isDisabled());
    const codingId = state.nodes[1].id;
    await page.getByLabel("Connect from", { exact: true }).selectOption(codingId);
    await page.getByRole("button", { name: /^Connect stages$/i }).click();
    check("WIP stages retain dependency connections", (await page.evaluate(() => window.adlcFixture.state().edges.length)) === 3);
    await page.getByRole("button", { name: "Close stage inspector" }).click();
    await page.getByRole("button", { name: "Fit workflow to canvas" }).click(); await page.waitForTimeout(300);
    await page.screenshot({ path: path.join(output, "workspace-light.png") });
    await page.getByRole("button", { name: "Toggle canvas overview" }).click();
    check("Canvas overview is available", await page.locator(".react-flow__minimap").isVisible());
    await page.getByRole("button", { name: "Focus canvas" }).click();
    check("Focus mode expands canvas past 85 percent of the screen", (await canvas.boundingBox()).width / 1440 > .85);
    check("Focus mode hides package library", await page.getByLabel("Package library", { exact: true }).count() === 0);
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await page.waitForFunction(() => document.body.textContent.includes("Saved workflow"));
    check("Save uses the existing flow persistence endpoint", patches > 0 && saved.data.nodes.length === 4 && saved.data.edges.length === 3);
    const savedViewport = await page.evaluate(() => window.adlcFixture.state().viewport);
    await page.evaluate(flow => localStorage.setItem("adlc-workspace-browser-fixture", JSON.stringify(flow)), saved);
    await page.reload({ waitUntil: "networkidle" });
    state = await page.evaluate(() => window.adlcFixture.state());
    check("Reopening restores WIP blocks, requirement, and edges", state.nodes.length === 4 && state.edges.length === 3 && state.nodes[0].data.adlcDraft.requirement.includes("CRUD"));
    check("Reopening restores viewport", Math.abs(state.viewport.zoom - savedViewport.zoom) < .01 && Math.abs(state.viewport.x - savedViewport.x) < 1);
    await page.evaluate(() => window.adlcFixture.lock(true));
    check("Locked workflow disables adding packages", await page.getByRole("button", { name: "Add Coding Agent", exact: true }).isDisabled());
    check("Locked workflow disables editing workflow details", await page.getByRole("button", { name: "Edit workflow details" }).isDisabled());
    check("Locked workflow preserves zoom", await page.getByRole("button", { name: "Zoom in", exact: true }).isEnabled());
    await page.evaluate(() => window.adlcFixture.lock(false));
    await page.getByRole("button", { name: "Focus canvas" }).click();
    await page.evaluate(() => window.adlcFixture.theme(true));
    await page.waitForTimeout(350);
    check("Dark theme keeps canvas controls readable", await page.getByRole("button", { name: "Zoom in", exact: true }).evaluate(el => Number(getComputedStyle(el).color.match(/\d+/)[0]) > 200));
    await page.screenshot({ path: path.join(output, "workspace-dark-focus.png") });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Fit workflow to canvas" }).click(); await page.waitForTimeout(300);
    check("Small screen canvas has useful height", (await canvas.boundingBox()).height > 500);
    check("Small screen has no page-wide horizontal overflow", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: path.join(output, "workspace-mobile.png") });
    await page.getByRole("button", { name: "Toggle package library" }).click();
    check("Small screens can open the package drawer", await page.getByLabel("Package library", { exact: true }).isVisible());
    await page.getByRole("button", { name: "Add Testing Agent", exact: true }).click();
    check("Small screens can add without dragging", (await page.evaluate(() => window.adlcFixture.state().nodes.length)) === 5);
    check("No browser script errors", errors.length === 0);
    console.log(JSON.stringify({ checks: checks.length, errors, screenshots: output }, null, 2));
  } catch (error) { await page.screenshot({ path: path.join(output, "failure.png") }).catch(() => {}); console.error(JSON.stringify({ errors, page: await page.locator("body").innerText().catch(() => "unavailable") })); throw error; }
  finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
